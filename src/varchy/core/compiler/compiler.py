"""Documentation Compiler and AI Agent Instruction Exporter."""

from pathlib import Path
from typing import Any

from varchy.core.models.blueprint import Blueprint
from varchy.core.storage.workspace import WorkspaceManager


class DocCompiler:
    """Compiles structured Pydantic blueprints into human- and agent-readable Markdown files."""

    def __init__(self, workspace: WorkspaceManager):
        self.workspace = workspace
        self.docs_dir = workspace.docs_dir

    def compile_all(self, blueprint: Blueprint) -> dict[str, Path]:
        """Compile complete documentation hierarchy and agent instructions."""
        written_files: dict[str, Path] = {}

        # 1. Product Docs
        p_dir = self.docs_dir / "01-product"
        p_dir.mkdir(parents=True, exist_ok=True)
        prd_path = p_dir / "prd.md"
        prd_content = self._render_prd(blueprint)
        prd_path.write_text(prd_content, encoding="utf-8")
        written_files["prd"] = prd_path

        # 2. Design Specs
        d_dir = self.docs_dir / "02-design"
        d_dir.mkdir(parents=True, exist_ok=True)
        screens_path = d_dir / "screens.md"
        screens_content = self._render_screens(blueprint)
        screens_path.write_text(screens_content, encoding="utf-8")
        written_files["screens"] = screens_path

        # 3. Engineering & Architecture
        e_dir = self.docs_dir / "03-engineering"
        e_dir.mkdir(parents=True, exist_ok=True)
        arch_path = e_dir / "architecture.md"
        arch_content = self._render_architecture(blueprint)
        arch_path.write_text(arch_content, encoding="utf-8")
        written_files["architecture"] = arch_path

        # 4. Development Tasks & Roadmap
        dev_dir = self.docs_dir / "04-development"
        dev_dir.mkdir(parents=True, exist_ok=True)
        tasks_path = dev_dir / "tasks.md"
        tasks_content = self._render_tasks(blueprint)
        tasks_path.write_text(tasks_content, encoding="utf-8")
        written_files["tasks"] = tasks_path

        # 5. Quality & Testing Strategy
        q_dir = self.docs_dir / "05-quality"
        q_dir.mkdir(parents=True, exist_ok=True)
        testing_path = q_dir / "testing.md"
        testing_content = self._render_testing(blueprint)
        testing_path.write_text(testing_content, encoding="utf-8")
        written_files["testing"] = testing_path

        # 6. Agent Instruction Files
        agents_md = self.workspace.root / "AGENTS.md"
        agents_md.write_text(self._render_agents_md(blueprint), encoding="utf-8")
        written_files["agents_md"] = agents_md

        claude_md = self.workspace.root / "CLAUDE.md"
        claude_md.write_text(self._render_claude_md(blueprint), encoding="utf-8")
        written_files["claude_md"] = claude_md

        gemini_md = self.workspace.root / "GEMINI.md"
        gemini_md.write_text(self._render_gemini_md(blueprint), encoding="utf-8")
        written_files["gemini_md"] = gemini_md

        return written_files

    def _render_prd(self, bp: Blueprint) -> str:
        lines = [
            f"# Product Requirements Document (PRD): {bp.metadata.name}",
            f"> Category: {bp.metadata.category.value} | Generated by Varchy",
            "",
            "## 1. Overview & Problem Statement",
            bp.product.overview,
            "",
            "### Problem Statement",
            bp.product.problem_statement,
            "",
            "### Product Vision",
            bp.product.vision,
            "",
            "## 2. Requirements & Traceability",
        ]
        for req in bp.product.requirements:
            lines.append(f"### [{req.id}] {req.title}")
            lines.append(f"- **Type:** {req.type.value} | **Priority:** {req.priority.value}")
            lines.append(f"- **Description:** {req.description}")
            if req.user_story:
                lines.append(f"- **User Story:** {req.user_story}")
            if req.acceptance_criteria:
                lines.append("- **Acceptance Criteria:**")
                for ac in req.acceptance_criteria:
                    lines.append(f"  - [ ] {ac}")
            lines.append("")
        return "\n".join(lines)

    def _render_screens(self, bp: Blueprint) -> str:
        lines = [
            f"# UI/UX Specification: {bp.metadata.name}",
            "",
            "## Information Architecture",
            bp.design.information_architecture,
            "",
            "## Screen Definitions",
        ]
        for s in bp.design.screens:
            lines.append(f"### [{s.id}] {s.title} (`{s.route_or_view}`)")
            lines.append(f"- **Purpose:** {s.purpose}")
            lines.append(f"- **Required Components:** {', '.join(s.required_components)}")
            lines.append(f"- **Actions:** {', '.join(s.actions)}")
            if s.interaction_states:
                lines.append("- **Interaction States:**")
                for state in s.interaction_states:
                    lines.append(f"  - **{state.state_name}:** {state.behavior}")
            lines.append("")
        return "\n".join(lines)

    def _render_architecture(self, bp: Blueprint) -> str:
        lines = [
            f"# Technical Architecture: {bp.metadata.name}",
            "",
            "## Technology Stack & Decisions",
            "| Category | Technology | Rationale |",
            "|---|---|---|",
        ]
        for t in bp.architecture.tech_stack:
            lines.append(f"| {t.category} | **{t.name}** | {t.justification} |")
        lines.append("")
        lines.append("## Service Boundaries")
        for sb in bp.architecture.service_boundaries:
            lines.append(f"### {sb.name}")
            lines.append(sb.description)
            for resp in sb.responsibilities:
                lines.append(f"- {resp}")
        lines.append("")
        lines.append("## Security Requirements")
        sec = bp.architecture.security
        lines.append(f"- **Authentication:** {sec.authentication}")
        lines.append(f"- **Authorization:** {sec.authorization}")
        lines.append(f"- **Secret Management:** {sec.secret_management}")
        lines.append(f"- **Input Validation:** {sec.input_validation}")
        lines.append(f"- **Rate Limiting:** {sec.rate_limiting}")
        lines.append("")
        return "\n".join(lines)

    def _render_tasks(self, bp: Blueprint) -> str:
        lines = [
            f"# Development Roadmap & Implementation Tasks: {bp.metadata.name}",
            "",
        ]
        phase_map = {p.id: p for p in bp.planning.phases}
        tasks_by_phase: dict[str, list[Any]] = {}
        for t in bp.planning.tasks:
            tasks_by_phase.setdefault(t.phase_id, []).append(t)

        for phase_id, phase in phase_map.items():
            lines.append(f"## {phase.name} (Objective: {phase.objective})")
            for t in tasks_by_phase.get(phase_id, []):
                deps = f" (Depends on: {', '.join(t.dependencies)})" if t.dependencies else ""
                lines.append(f"### [{t.id}] {t.title}{deps}")
                lines.append(f"- **Description:** {t.description}")
                lines.append(f"- **Realizes:** {', '.join(t.requirement_ids)}")
                if t.completion_criteria:
                    lines.append("- **Completion Criteria:**")
                    for cc in t.completion_criteria:
                        lines.append(f"  - [ ] {cc}")
                lines.append("")
        return "\n".join(lines)

    def _render_testing(self, bp: Blueprint) -> str:
        lines = [
            f"# Testing Strategy & Quality Assurance: {bp.metadata.name}",
            "",
            "## Strategy Overview",
            bp.testing.overall_strategy,
            "",
            "## Verification Test Cases",
        ]
        for tc in bp.testing.test_cases:
            lines.append(f"### [{tc.id}] {tc.title} ({tc.type.value})")
            lines.append(f"- **Validates:** `{tc.target_id}` | **Edge Case:** {tc.is_edge_case}")
            lines.append(f"- **Expected Result:** {tc.expected_result}")
            if tc.steps:
                lines.append("- **Execution Steps:**")
                for idx, step in enumerate(tc.steps, 1):
                    lines.append(f"  {idx}. {step}")
            lines.append("")
        return "\n".join(lines)

    def _render_agents_md(self, bp: Blueprint) -> str:
        return f"""# AGENTS.md — AI Coding Agent Architecture Instructions
**Project:** {bp.metadata.name}  
**Architecture Spec Version:** {bp.metadata.varchy_version}  

## 🎯 Ground Rules for AI Coding Agents
1. **Never make up architecture on the fly:** Always check `docs/03-engineering/architecture.md`.
2. **Follow Task Sequence:** Implement tasks ordered by `docs/04-development/tasks.md`.
3. **Verify Acceptance Criteria:** Every implemented task must fulfill its associated requirement acceptance criteria in `docs/01-product/prd.md`.
4. **Enforce Test Gates:** Implement tests in `docs/05-quality/testing.md` before marking any task complete.

## 📖 Documentation Reading Order
1. [PRD](docs/01-product/prd.md)
2. [Architecture](docs/03-engineering/architecture.md)
3. [Design & Screens](docs/02-design/screens.md)
4. [Tasks](docs/04-development/tasks.md)
5. [Testing](docs/05-quality/testing.md)
"""

    def _render_claude_md(self, bp: Blueprint) -> str:
        return f"""# CLAUDE.md — Claude Code Guidelines for {bp.metadata.name}

## Project Overview
{bp.metadata.description}

## Workflow & Coding Standards
- Read `docs/04-development/tasks.md` before choosing a task.
- Follow technology choices in `docs/03-engineering/architecture.md`.
- Keep changes minimal and maintain documentation consistency.
"""

    def _render_gemini_md(self, bp: Blueprint) -> str:
        return f"""# GEMINI.md — Gemini Instructions for {bp.metadata.name}

## Project Summary
{bp.metadata.description}

Refer to `docs/` for all architectural specifications and stable requirement IDs.
"""

